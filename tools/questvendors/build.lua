-- Builds GearPilotPro/Data/QuestVendors.lua: every vendor (with its place and faction) of every item a quest asks for.
-- ForeverDB caps its vendor lists at 30 entries, so the nearest vendor of a quest item can be missing; this table
-- takes the full lists from ForeverDB_Full (same package, GPL-3.0) for the few items quests need.
-- Usage: lua5.1 tools/questvendors/build.lua <forever-db checkout> <output file>
local dir, out = arg[1], arg[2]
assert(dir and out, "usage: build.lua <forever-db folder> <output file>")

local function load(folder, prefix, count)
    for i = 1, count do
        local path = ("%s/%s/%s%s.lua"):format(dir, folder, prefix, i == 1 and "" or ("_" .. i))
        local f = io.open(path, "rb")
        if f then f:close(); dofile(path) end
    end
end
load("ForeverDB", "ForeverDB", 9)
load("ForeverDB_Full", "ForeverDB_Full", 9)
local D, F = assert(ForeverDB, "ForeverDB missing"), ForeverDBFull or {}

-- Items quests ask for (qx[10]).
local wanted = {}
for _, detail in pairs(D.qx or {}) do
    for _, itemID in ipairs(type(detail[10]) == "table" and detail[10] or {}) do wanted[itemID] = true end
end

local items, total, vendorsSeen = {}, 0, 0
for itemID in pairs(wanted) do
    local list = (F.vend and F.vend[itemID]) or (D.vend and D.vend[itemID])
    if type(list) == "table" and #list > 0 then
        local rows = {}
        for _, npcID in ipairs(list) do
            local spawns = (D.spw and D.spw["c" .. npcID]) or (F.spw and F.spw["c" .. npcID])
            local side = D.nfac and D.nfac[npcID] or ""
            for _, s in ipairs(type(spawns) == "table" and spawns or {}) do
                if type(s[2]) == "number" and type(s[3]) == "number" then
                    rows[#rows + 1] = { npcID, s[1], math.floor(s[2] + .5), math.floor(s[3] + .5), side }
                    vendorsSeen = vendorsSeen + 1
                end
            end
        end
        table.sort(rows, function(a, b)
            if a[1] ~= b[1] then return a[1] < b[1] end
            if a[3] ~= b[3] then return a[3] < b[3] end
            return a[4] < b[4]
        end)
        if #rows > 0 then items[#items + 1] = { itemID, rows }; total = total + 1 end
    end
end
table.sort(items, function(a, b) return a[1] < b[1] end)

local f = assert(io.open(out, "wb"))
f:write("-- Generated by tools/questvendors/build.lua from ForeverDB / ForeverDB_Full (GPL-3.0) - do not edit.\n")
f:write("-- [itemID] = { vendorID, continent, y, x, faction, vendorID, ... } - five numbers per place, one flat list per\n")
f:write("-- item (fewer tables, less memory); faction: 0 = any, 1 = Alliance, 2 = Horde, 3 = both.\n")
f:write("local _, GP = ...\n")
f:write(("GP.QuestVendors = { build = %q,\n"):format(tostring(D.meta and D.meta.build or "?")))
for _, entry in ipairs(items) do
    local parts = {}
    local code = { A = 1, H = 2, AH = 3 }
    for _, r in ipairs(entry[2]) do parts[#parts + 1] = ("%d,%d,%d,%d,%d"):format(r[1], r[2], r[3], r[4], code[r[5]] or 0) end
    f:write(("[%d]={%s},\n"):format(entry[1], table.concat(parts, ",")))
end
f:write("}\n")
f:close()
print(("%d quest items with vendors, %d vendor places"):format(total, vendorsSeen))
